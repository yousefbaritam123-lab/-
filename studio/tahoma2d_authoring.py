"""Create safe Tahoma2D authoring inputs and ToonzScript for a native scene pilot.

This does not create Plastic meshes or skeletons. It prepares transparent image
levels from the preserved character references and asks Tahoma2D itself to save
the native .tnz scene through its documented ToonzScript API.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Iterable


def prepare_scene_levels(project_dir: Path, output_dir: Path, *, width: int = 1920,
                         height: int = 1080) -> list[Path]:
    project = Path(project_dir).resolve()
    output = Path(output_dir).resolve()
    output.mkdir(parents=True, exist_ok=True)
    try:
        import cairosvg
        from PIL import Image
    except ImportError as exc:
        raise RuntimeError("Install CairoSVG and Pillow to prepare Tahoma2D scene levels") from exc

    placements = {"youssef": (300, 110), "adam": (1200, 110)}
    levels: list[Path] = []
    for character, (x, y) in placements.items():
        reference = project / "production" / "tahoma2d" / "characters" / character / "full_character_reference.svg"
        if not reference.is_file():
            raise FileNotFoundError(f"Prepared original reference is missing: {reference}")
        rendered = output / f"{character}_source.png"
        cairosvg.svg2png(url=str(reference), write_to=str(rendered),
                         output_width=380, output_height=835)
        with Image.open(rendered) as source:
            rgba = source.convert("RGBA")
        canvas = Image.new("RGBA", (width, height), (0, 0, 0, 0))
        canvas.alpha_composite(rgba, (x, y))
        level_path = output / f"{character}_level.png"
        canvas.save(level_path)
        levels.append(level_path)
    metadata = {
        "schema_version": 1,
        "engine": "Tahoma2D",
        "mode": "native_scene_import_smoke_test",
        "source_art_preserved": True,
        "camera": {"width": width, "height": height},
        "levels": [str(p) for p in levels],
        "plastic_meshes": "not_authored",
        "plastic_skeletons": "not_authored",
        "note": "Static source-art levels prove native scene import and render only; they are not an animation or rig certification."
    }
    (output / "scene_input_manifest.json").write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return levels


def write_toonzscript(scene_path: Path, level_paths: Iterable[Path],
                      script_path: Path, *, frames: int = 24) -> Path:
    scene_path = Path(scene_path).resolve()
    script_path = Path(script_path).resolve()
    levels = [Path(p).resolve() for p in level_paths]
    if len(levels) < 1 or frames < 1:
        raise ValueError("At least one level and one frame are required")
    for path in levels:
        if not path.is_file():
            raise FileNotFoundError(path)
    def js(value: Path) -> str:
        return json.dumps(str(value).replace("\\", "/"))
    lines = [
        "// Generated by studio.tahoma2d_authoring; executed inside Tahoma2D.",
        "var scene = new Scene();",
    ]
    names = []
    for index, level in enumerate(levels):
        name = f"Character_{index + 1}"
        names.append(name)
        lines.append(f"var level{index + 1} = scene.loadLevel({json.dumps(name)}, {js(level)});")
    for frame in range(frames):
        for index in range(len(levels)):
            lines.append(f"scene.setCell({frame}, {index}, level{index + 1}, 1);")
    lines.extend([
        f"scene.save({js(scene_path)});",
        f'print("TAHOMA2D_NATIVE_SCENE_SAVED", {json.dumps(str(scene_path))});',
    ])
    scene_path.parent.mkdir(parents=True, exist_ok=True)
    script_path.parent.mkdir(parents=True, exist_ok=True)
    script_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return script_path


def authoring_report(scene_path: Path, render_path: Path) -> dict:
    scene = Path(scene_path)
    render = Path(render_path)
    return {
        "native_scene_exists": scene.is_file() and scene.stat().st_size > 0,
        "native_scene_bytes": scene.stat().st_size if scene.is_file() else 0,
        "render_exists": render.is_file() and render.stat().st_size > 1024,
        "render_bytes": render.stat().st_size if render.is_file() else 0,
        "plastic_meshes": "not_verified",
        "plastic_skeletons": "not_verified",
    }
